def vector(body, w, h, name):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {MARKER}. Replace with hand-made art of the same name ({name}) at any time. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{w}dp"\n    android:height="{h}dp"\n'
        f'    android:viewportWidth="{w}"\n    android:viewportHeight="{h}">\n'
        + "\n".join(body)
        + "\n</vector>\n"
    )


def placeholder(word_id):
    """Fallback art for a word that has no design yet: a soft disc with a dot."""
    return [C(50, 50, 40, "#C7B8EA"), C(50, 50, 10, WHITE)]


def write(name, text, force):
    path = OUT / f"{name}.xml"
    if path.exists() and not force and MARKER not in path.read_text(encoding="utf-8"):
        print(f"skip {name} (hand-made art)")
        return False
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def main():
    force = "--force" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    words = json.loads((CONTENT / "words.json").read_text(encoding="utf-8"))["words"]
    designs = art()
    missing, changed = [], 0
    for w in words:
        body = designs.get(w["id"])
        if body is None:
            missing.append(w["id"])
            body = placeholder(w["id"])
        changed += write(w["image"], vector(body, 100, 100, w["image"]), force)
    for scene, body in backgrounds().items():
        changed += write(f"bg_{scene}", vector(body, 200, 120, f"bg_{scene}"), force)
    print(f"{len(words)} words, {changed} files written")
