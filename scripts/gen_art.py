# ---------------------------------------------------------------- primitives
def _path(d, fill=None, stroke=None, width=0.0, alpha=1.0, cap="round"):
    attrs = [f'android:pathData="{d}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
        if alpha < 1:
            attrs.append(f'android:fillAlpha="{alpha}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
        attrs.append(f'android:strokeWidth="{width}"')
        attrs.append(f'android:strokeLineCap="{cap}"')
        attrs.append('android:strokeLineJoin="round"')
    return "    <path " + " ".join(attrs) + " />"


def E(cx, cy, rx, ry, fill=None, stroke=None, width=0.0, alpha=1.0):
    d = f"M{cx - rx:g},{cy:g} a{rx:g},{ry:g} 0 1,0 {2 * rx:g},0 a{rx:g},{ry:g} 0 1,0 {-2 * rx:g},0 Z"
    return _path(d, fill, stroke, width, alpha)


def C(cx, cy, r, fill=None, stroke=None, width=0.0, alpha=1.0):
    return E(cx, cy, r, r, fill, stroke, width, alpha)


def R(x, y, w, h, fill=None, r=0.0, stroke=None, width=0.0, alpha=1.0):
    r = min(r, w / 2, h / 2)
    if r <= 0:
        d = f"M{x:g},{y:g} h{w:g} v{h:g} h{-w:g} Z"
    else:
        d = (
            f"M{x + r:g},{y:g} h{w - 2 * r:g} a{r:g},{r:g} 0 0,1 {r:g},{r:g} v{h - 2 * r:g} "
            f"a{r:g},{r:g} 0 0,1 {-r:g},{r:g} h{-(w - 2 * r):g} a{r:g},{r:g} 0 0,1 {-r:g},{-r:g} "
            f"v{-(h - 2 * r):g} a{r:g},{r:g} 0 0,1 {r:g},{-r:g} Z"
        )
    return _path(d, fill, stroke, width, alpha)


def P(d, fill=None, stroke=None, width=0.0, alpha=1.0):
    return _path(d, fill, stroke, width, alpha)


def L(points, stroke, width=4.0):
    d = "M" + " L".join(f"{x:g},{y:g}" for x, y in points)
    return _path(d, None, stroke, width)


def S(d, stroke, width=4.0):
    """Stroke-only path."""
    return _path(d, None, stroke, width)


def eye(x, y, r=3.5):
    return [C(x, y, r, INK), C(x + r * 0.35, y - r * 0.35, r * 0.35, WHITE)]


def star_points(cx, cy, outer, inner, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        rad = outer if i % 2 == 0 else inner
        a = math.radians(rot + i * 180 / n)
        pts.append((cx + rad * math.cos(a), cy + rad * math.sin(a)))
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"


def closed_eye(x, y, w=5):
    return S(f"M{x - w:g},{y:g} Q{x:g},{y + w * 0.9:g} {x + w:g},{y:g}", INK, 2.5)


